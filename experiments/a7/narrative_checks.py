"""Scope statistics quoted in NARRATIVE_REPORT.md after the hard auto-review (2026-09-29, run 2 round 1).

Reads only stored results (main_grid.csv, ablation_gaps.csv, ablation_stress.csv) and writes
results/narrative_checks.{json,md}. No new simulation.
"""
import json
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
RES = HERE / 'results'


def main():
    mg = pd.read_csv(RES / 'main_grid.csv')
    prim = mg[(mg.eps_over_lambda > 0) & ((mg.xP != 0) | (mg.yP != 0))]
    other = prim[(prim.Gamma <= 0) & (prim.xP != 0)]
    x0 = prim[prim.xP == 0]
    frac = x0.survivors / x0.family_size
    st = pd.read_csv(RES / 'ablation_stress.csv')
    s = st[(st.control == 'free') & np.isclose(st.xP, 6) & np.isclose(st.yP, 1) & np.isclose(st.eps_over_lambda, 0.03)
           & (st.snr_db == 40) & (st.role == 'hat')].iloc[0]
    total = np.log(s.U_plus / s.L0)
    out = dict(
        inconclusive_off_axis=dict(n=int(len(other)), median_gamma=float(other.Gamma.median()),
                                   below_minus_5pct=int((other.Gamma < -0.05).sum()), min_gamma=float(other.Gamma.min())),
        cap_hits=dict(primary=int(prim.capped.sum()), full_grid=int(mg.capped.sum()),
                      full_grid_P_eq_D=int(mg[(mg.xP == 0) & (mg.yP == 0)].capped.sum())),
        coaligned_main_grid_survivor_fraction=dict(min=float(frac.min()), median=float(frac.median()), max=float(frac.max())),
        exact_not_unique_primary=int(((prim.exact == 1) & (prim.unique == 0)).sum()),
        primary_cases=int(len(prim)),
        stress_enclosure_example=dict(case='free, P=(6,1), eps=0.03 lambda, 40 dB, S_hat',
                                      total_gap=float(s.U_plus / s.L0 - 1), dependency_upper=float(s.dep_hi),
                                      enclosure_share_of_log_gap_lower=float(1 - np.log1p(s.dep_hi) / total)),
    )
    (RES / 'narrative_checks.json').write_text(json.dumps(out, indent=1))
    e = out['stress_enclosure_example']
    L = ['# Narrative scope checks (generated by narrative_checks.py)', '',
         '- Off-axis inconclusive cases: %d; median Gamma %.2f%%; %d below -5%%; minimum %.2f%%.' % (
             out['inconclusive_off_axis']['n'], 100 * out['inconclusive_off_axis']['median_gamma'],
             out['inconclusive_off_axis']['below_minus_5pct'], 100 * out['inconclusive_off_axis']['min_gamma']),
         '- Screening-cap hits: %d primary; %d in the full grid (%d at P = D).' % (
             out['cap_hits']['primary'], out['cap_hits']['full_grid'], out['cap_hits']['full_grid_P_eq_D']),
         '- Main-grid co-aligned (x_P = 0) survivor fraction: %.2f%% to %.0f%% (median %.0f%%).' % (
             100 * out['coaligned_main_grid_survivor_fraction']['min'], 100 * out['coaligned_main_grid_survivor_fraction']['max'],
             100 * out['coaligned_main_grid_survivor_fraction']['median']),
         '- Primary cases with a completed scan but no uniqueness certificate: %d of %d.' % (
             out['exact_not_unique_primary'], out['primary_cases']),
         '- Stress example (%s): total gap %.3f%%; dependency <= %.4f%%; enclosure share of the log gap >= %.1f%% (rounded down).' % (
             e['case'], 100 * e['total_gap'], 100 * e['dependency_upper'],
             np.floor(1000 * e['enclosure_share_of_log_gap_lower']) / 10)]
    (RES / 'narrative_checks.md').write_text('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
